// Builds demo/ai-interview.html: one self-contained file that runs without a server.
// It inlines the same modules the Node server uses, so behavior stays identical.
//   node build-html.mjs

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFile(join(root, p), "utf8");

/** Turns an ES module into plain script code by removing import/export syntax. */
function stripModule(code, name) {
  const out = code
    .replace(/^import[\s\S]*?from\s+"[^"]+";[ \t]*$/gm, "")
    .replace(/^export (?=(async )?function |const |class |let )/gm, "");
  if (/^\s*(import|export)\b/m.test(out)) throw new Error(`${name}: unsupported import/export left after stripping`);
  return out;
}

// The page embeds JS inside <script>; make sure no source can close the tag early.
const safeScript = (code) => code.replace(/<\/script/gi, "<\\/script");

export async function buildHtml() {
  const [html, css, settings, config, providers, interview, handlers, localBackend, app] = await Promise.all([
    read("public/index.html"),
    read("public/styles.css"),
    read("html/settings-fields.html"),
    read("lib/config.mjs"),
    read("lib/providers.mjs"),
    read("lib/interview.mjs"),
    read("lib/handlers.mjs"),
    read("html/local-backend.js"),
    read("public/app.js"),
  ]);

  const backend = [
    stripModule(config, "config.mjs"),
    stripModule(providers, "providers.mjs"),
    stripModule(interview, "interview.mjs"),
    stripModule(handlers, "handlers.mjs"),
    localBackend,
  ].join("\n");

  const extraCss = `
.key-box { background: var(--brand-soft); border-radius: 10px; padding: 12px 14px; }
.key-title { font-weight: 600; font-size: 14px; margin-bottom: 4px; }
.key-box a { color: var(--brand-dark); }`;

  let out = html;
  const replace = (needle, value) => {
    if (!out.includes(needle)) throw new Error(`build-html: marker not found: ${needle}`);
    out = out.replace(needle, () => value);
  };
  replace('<link rel="stylesheet" href="/styles.css" />', `<style>\n${css}\n${extraCss}\n</style>`);
  replace('<script type="module" src="/app.js"></script>', "");
  replace('        <label class="check span-2">\n          <input type="checkbox" id="camera"', `${settings}        <label class="check span-2">\n          <input type="checkbox" id="camera"`);
  replace(
    "  </body>",
    `    <script>
// Generated by demo/build-html.mjs from demo/lib/*.mjs and demo/public/app.js. Do not edit by hand.
window.ADI_LOCAL_BACKEND = (() => {
${safeScript(backend)}
})();
    </script>
    <script>
(() => {
${safeScript(app)}
})();
    </script>
  </body>`,
  );
  return out;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const out = await buildHtml();
  await writeFile(join(root, "ai-interview.html"), out);
  console.log(`Wrote demo/ai-interview.html (${Math.round(out.length / 1024)} KB)`);
}
